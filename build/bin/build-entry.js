const glob = require('glob')
const fs = require('fs')
const fse = require('fs-extra')
const render = require('json-templater/string')
const path = require('path')
const endOfLine = require('os').EOL
const shell = require('shelljs')
const pkg = require('../../package.json')
const utils = require('../utils')

const OUTPUT_PATH = path.join(utils.ROOT_PATH, 'src/index.js')
const FILE_PATHS = glob.sync('./src/*/**.{js,ts}').map(v => v.replace('src/', ''))

const EXCLUDE_DIRS = ['expand', 'nodejs'] // 排出的文件夹

const EXCLUDE_FILES = ['_constant', '__test'] // 排出的文件

fse.ensureFileSync(OUTPUT_PATH)
fs.writeFileSync(OUTPUT_PATH, '')

const IMPORT_TEMPLATE = "import {{name}} from '{{package}}'"
const MAIN_TEMPLATE = `/* Author：bianpengfei Automatically generated by './bin/${path.basename(__filename)}' */

{{import}}

const version = '{{version}}'

const ${pkg.globalName} = {
   version,
  {{modules}}
}

/**
* @params {Object} ${pkg.globalName} 全局家
*/
export default ${pkg.globalName}

export {
  version,
  {{modules}}
}

`
// const global = getGlobalThis()
// def(global, '$sf', ${pkg.globalName})

const importTemplate = []
const ModulesTemplate = []

FILE_PATHS.forEach(v => {
  const pathSplit = v.replace(/^\.\/(.*)\.\w+$/, '$1').split('/')
  const moduleName = pathSplit.slice().pop()
  const dirs = pathSplit.slice(0, -1).map(v => v.match(/(\d+\.)?(.*)/)?.[2])

  if (!EXCLUDE_DIRS.includes(dirs[0]) && !EXCLUDE_FILES.includes(moduleName)) {
    importTemplate.push(
      render(IMPORT_TEMPLATE, {
        name: moduleName,
        package: v
      })
    )
    ModulesTemplate.push(`\t${moduleName}`)
  }
})

const template = render(MAIN_TEMPLATE, {
  import: importTemplate.join(endOfLine),
  modules: ModulesTemplate.join(',' + endOfLine),
  version: process.env.VERSION || pkg.version
})

fs.writeFileSync(OUTPUT_PATH, template)

const PRETTIER_PATH = path.join(utils.ROOT_PATH, '.prettierrc.js')

if (shell.exec(`prettier ${OUTPUT_PATH} --config --ignore-unknown ${PRETTIER_PATH} --write`).code !== 0) {
  shell.exit(1)
}

console.log('[build entry] DONE:', OUTPUT_PATH)
